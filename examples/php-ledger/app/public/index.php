}

function transfer_form(string $from, string $to, string $amount, string $key, string $label): string
{
    return sprintf(
        '<form method="post" action="/transfer">'
        . 'from <input name="from" value="%s"> to <input name="to" value="%s"> '
        . 'amount (cents) <input name="amount_cents" value="%s">'
        . '<input type="hidden" name="idempotency_key" value="%s">'
        . ' <button type="submit">%s</button></form>',
        h($from), h($to), h($amount), h($key), h($label),
    );
}

if ($method === 'POST' && $path === '/transfer') {
    $from = (string) ($_POST['from'] ?? '');
    $to = (string) ($_POST['to'] ?? '');
    $amountRaw = (string) ($_POST['amount_cents'] ?? '');
    $key = (string) ($_POST['idempotency_key'] ?? '');
    $amount = filter_var($amountRaw, FILTER_VALIDATE_INT);
    if ($amount === false) {
        page('<p>Amount must be an integer number of cents.</p><p><a href="/">back</a></p>', 400);
    }
    // The key is generated by the server when the form is rendered (GET /). The broker enforces
    // the format; this check only gives a clearer message for a missing or stale form.
    if (preg_match('/^[A-Za-z0-9_-]{16,64}$/D', $key) !== 1) {
        page('<p id="result">Missing or invalid idempotency key: reload the form.</p><p><a href="/">back</a></p>', 400);
    }
    try {
        $r = $broker->transfer($from, $to, $amount, $key);
        page(sprintf(
            '<p id="result">TRANSFER OK id=%d%s: %d cents %s &rarr; %s. New %s balance: %d cents.</p><p><a href="/">back</a></p>',
            $r['transfer_id'], ($r['replayed'] ?? false) === true ? ' (already completed earlier; not charged again)' : '',
            $r['amount_cents'], h($r['from']), h($r['to']), h($r['from']), $r['from_balance_cents'],
        ));
    } catch (BrokerError $e) {
        $cid = h((string) $e->correlationId);
        // bad_response on an effectful call means we cannot tell what happened: treat it as unknown.
        if ($e->errorCode === 'outcome_unknown' || $e->errorCode === 'bad_response') {
            // The transfer may have committed. Never call this "denied": that invites a retry
            // with a new key, i.e. a second debit (review D1-01).
            page(
                '<p id="result">OUTCOME UNKNOWN &mdash; the transfer may have completed; resubmitting this same form '
                . 'is safe (it will not charge twice).</p>'
                . '<p>correlation id ' . $cid . '</p>'
                . transfer_form($from, $to, $amountRaw, $key, 'Resubmit this same transfer')
                . '<p><a href="/">back</a></p>',
                502,
            );
        }
        if ($e->errorCode === 'unavailable') {
            page(sprintf(
                // "Not executed" is true only of THIS request: an earlier submission of the same
                // form (same key) may still be committing, so never claim nothing was charged
                // (review ID-01).
                '<p id="result">NOT EXECUTED BY THIS REQUEST: service unavailable (%s). If this form was '
                . 'submitted before, that earlier submission may still complete. Resubmitting this same '
                . 'form is safe: it will not charge twice.</p>%s<p><a href="/">back</a></p>',
                h($e->getMessage()), transfer_form($from, $to, $amountRaw, $key, 'Resubmit this same transfer'),
            ), 503);
        }
        page(sprintf(
            '<p id="result">TRANSFER DENIED: %s (%s), correlation id %s</p><p><a href="/">back</a></p>',
            h($e->errorCode), h($e->getMessage()), $cid,
        ), 403);
    }
}

